#!/usr/bin/env python3
"""
benchmark_oracles.py — measured accuracy of the overlap spine vs the oracle crosswalks.

The repo ships production-derived "overlap oracle" combination crosswalks
(cross-mapping/core-audit/mappings/*.csv + overlap-data/) that CLAUDE.md designates
ground truth for validation.  This benchmark turns them into published, pinned
precision/recall numbers at two layers:

  Layer 1 — ER-level (no DB needed): the computed shared-ER set for each oracle
    pair (via the existing er_overlap engine — reused, not reimplemented) scored
    against the oracle's authoritative shared set.  Precision / recall / F1.

  Layer 2 — spine-level (needs a built grc.db): the native control ids the
    production oracle co-cites with SOC 2 scored against the ids that appear on
    dbz's master_mappings edges for the same framework pair.
      * "oracle_coverage"  = fraction of oracle-co-cited ids recovered by the
        spine (a true recall against ground truth).
      * "corroboration_rate" = fraction of the spine's edge ids that the oracle
        co-cites.  This is NOT raw precision — the oracle is one production
        sample, so a spine id absent from it is unconfirmed, not wrong.  It is
        reported under its honest name.
    Joinability per pair:
      ISO 27001/2 (2022) — joinable (both sides use normalize_iso_id forms).
      HITRUST            — joinable at control level via the id structure that
                           HITRUST's own e1 statement ids embed
                           ('0701.07a1Organizational.8' -> control '07.a').
      HIPAA Security     — NOT joinable (the oracle's HIPAA side uses
                           provider-proprietary ids); ER layer only.

Honesty rules: oracle rows that fail to parse are counted and reported, never
silently dropped; provider-proprietary identifiers (ER-/REQ- ids) never appear
in any output — aggregate counts only; thresholds are pinned BELOW measured
values (measure-then-pin), never aspirational.

Usage:
  python benchmark_oracles.py            # measure + print table
  python benchmark_oracles.py --check    # exit 1 if any metric fell below its pin
  python benchmark_oracles.py --json OUT # also write aggregate JSON
  python benchmark_oracles.py --write-doc  # refresh the generated table in docs/BENCHMARK.md
"""

import argparse
import csv
import json
import re
import sqlite3
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
ENGINE_DIR = REPO_ROOT / "cross-mapping" / "engine"
sys.path.insert(0, str(ENGINE_DIR))

import er_overlap  # noqa: E402  (reuse the canonical parser/calculator)

DB_PATH = REPO_ROOT / "cross-mapping" / "output" / "grc.db"
DOC_PATH = REPO_ROOT / "docs" / "BENCHMARK.md"
DOC_BEGIN = "<!-- BENCHMARK-TABLE:BEGIN (generated by cross-mapping/tests/benchmark_oracles.py --write-doc; do not edit by hand) -->"
DOC_END = "<!-- BENCHMARK-TABLE:END -->"

# Which primary CSV feeds each oracle pair (mirrors er_overlap.run_validation).
ORACLE_SOURCE_CSV = {
    ("SOC 2", "ISO 27001/2 (2022)"): "SOC 2 T2",
    ("SOC 2", "HIPAA Security"): "SOC 2 T1",
    ("SOC 2", "HITRUST"): "SOC 2 T2",
}

# Master-surface framework labels for the layer-2 join (grc.db framework_labels
# canonical names), plus the oracle-side framework label inside the oracle CSV.
LAYER2_JOIN = {
    ("SOC 2", "ISO 27001/2 (2022)"): {
        "master_fw": "ISO 27001/2 (2022)",
        "oracle_fw": "ISO 27001/2 (2022)",
        "normalize": "iso",
    },
    ("SOC 2", "HITRUST"): {
        "master_fw": "HITRUST CSF",
        "oracle_fw": "HITRUST",  # the oracle CSV labels its e1 statement ids plain "HITRUST"
        "normalize": "hitrust_control",
    },
    # ("SOC 2", "HIPAA Security") is deliberately absent: the oracle's HIPAA side
    # carries provider-proprietary ids, so no spine-level join exists.
}

# ── pinned thresholds (measure-then-pin: recorded from the 2026-07-17 run and
#    set 2-3 points BELOW measured so CI catches regressions without flapping.
#    Re-measure -> re-pin -> CHANGELOG entry when data legitimately changes;
#    never delete a pin, never pin above measured reality.) ──────────────────
MIN_LAYER1 = {
    # (fw_a, fw_b): {"precision": x, "recall": y}   measured values in comments
    ("SOC 2", "ISO 27001/2 (2022)"): {"precision": 0.97, "recall": 0.97},  # measured 1.000 / 1.000 (2026-07-17)
    ("SOC 2", "HIPAA Security"): {"precision": 0.97, "recall": 0.97},      # measured 1.000 / 1.000 (2026-07-17)
    ("SOC 2", "HITRUST"): {"recall": 0.97},  # measured recall 1.000 (2026-07-17); precision unpinned (e1-scoped oracle -> superset expected, measured 0.732)
}
MIN_LAYER2 = {
    ("SOC 2", "ISO 27001/2 (2022)"): {"oracle_coverage": 0.52},  # measured 0.553 (2026-07-17)
    ("SOC 2", "HITRUST"): {"oracle_coverage": 0.59},             # measured 0.622 (2026-07-17)
}


def _count_csv_rows(path: Path):
    """Total data rows vs rows the parser accepts (has a Reference ID)."""
    total = parsed = 0
    with open(path, encoding="utf-8-sig") as f:
        for row in csv.DictReader(f):
            total += 1
            if (row.get("Reference ID") or "").strip():
                parsed += 1
    return total, total - parsed


def _prf(computed: set, truth: set):
    inter = len(computed & truth)
    p = inter / len(computed) if computed else 0.0
    r = inter / len(truth) if truth else 0.0
    f1 = 2 * p * r / (p + r) if (p + r) else 0.0
    return round(p, 3), round(r, 3), round(f1, 3)


def layer1_er_benchmark():
    """ER-level P/R/F1 per oracle pair. Reuses er_overlap end to end."""
    crosswalks = er_overlap.load_all_crosswalks()
    results = []
    for (fw_a, fw_b), oracle_path in er_overlap.ORACLE_FILES.items():
        source_cw = crosswalks.get(ORACLE_SOURCE_CSV[(fw_a, fw_b)])
        if source_cw is None or not oracle_path.exists():
            results.append({"pair": [fw_a, fw_b], "status": "skipped",
                            "reason": "source or oracle file missing"})
            continue
        computed = set(er_overlap.compute_er_overlap(
            source_cw, fw_a, source_cw, fw_b)["overlap"]["shared_er_ids"])
        oracle_cw = er_overlap.ERCrosswalk(oracle_path)
        truth = oracle_cw.er_set_for(fw_a)
        total, unparsed = _count_csv_rows(oracle_path)
        p, r, f1 = _prf(computed, truth)
        superset_ok = (fw_a, fw_b) in er_overlap.ORACLE_SUPERSET_OK
        results.append({
            "pair": [fw_a, fw_b], "status": "ok", "layer": "er",
            "oracle_file": oracle_path.name,
            "oracle_rows": total, "unparsed_rows": unparsed,
            "oracle_shared": len(truth), "computed_shared": len(computed),
            "precision": p, "recall": r, "f1": f1,
            "superset_expected": superset_ok,
        })
    return results


_HITRUST_STMT = re.compile(r"^\d{4}\.(\d{2})([a-z])")


def _hitrust_control(stmt_id: str):
    """HITRUST e1 statement id -> control ref its own structure embeds
    ('0701.07a1Organizational.8' -> '07.a'). Unrecognized -> None (never guess)."""
    m = _HITRUST_STMT.match(stmt_id.strip())
    return f"{m.group(1)}.{m.group(2)}" if m else None


def layer2_spine_benchmark():
    """Spine-level oracle_coverage / corroboration_rate per joinable pair."""
    if not DB_PATH.exists():
        return [{"status": "skipped", "reason": "grc.db not built (layer 2 needs a build)"}]
    conn = sqlite3.connect(DB_PATH)
    results = []
    for (fw_a, fw_b), join in LAYER2_JOIN.items():
        oracle_path = er_overlap.ORACLE_FILES[(fw_a, fw_b)]
        if not oracle_path.exists():
            results.append({"pair": [fw_a, fw_b], "status": "skipped",
                            "reason": "oracle file missing"})
            continue
        oracle_cw = er_overlap.ERCrosswalk(oracle_path)
        oracle_ids = set(oracle_cw.native_control_set_for(join["oracle_fw"]))

        # master edge ids on the joinable side for this pair (fw ordering in
        # master_mappings is canonical; query both orientations to be safe)
        mfw = join["master_fw"]
        rows = conn.execute(
            "SELECT native_a FROM master_mappings WHERE fw_a=? AND fw_b='SOC 2' "
            "UNION SELECT native_b FROM master_mappings WHERE fw_b=? AND fw_a='SOC 2'",
            (mfw, mfw)).fetchall()
        master_ids = {r[0] for r in rows}

        unmapped = 0
        if join["normalize"] == "hitrust_control":
            derived = set()
            for sid in oracle_ids:
                c = _hitrust_control(sid)
                if c is None:
                    unmapped += 1
                else:
                    derived.add(c)
            oracle_ids = derived
            # master HITRUST natives are 'NN.x Title' — compare on the 'NN.x' key
            master_ids = {m.split(" ")[0] for m in master_ids}

        inter = oracle_ids & master_ids
        coverage = len(inter) / len(oracle_ids) if oracle_ids else 0.0
        corrob = len(inter) / len(master_ids) if master_ids else 0.0
        results.append({
            "pair": [fw_a, fw_b], "status": "ok", "layer": "spine",
            "join_granularity": join["normalize"],
            "oracle_cocited_ids": len(oracle_ids),
            "oracle_ids_unmapped": unmapped,
            "master_edge_ids": len(master_ids),
            "intersection": len(inter),
            "oracle_coverage": round(coverage, 3),
            "corroboration_rate": round(corrob, 3),
        })
    conn.close()
    return results


def run_benchmark():
    return {"layer1_er": layer1_er_benchmark(), "layer2_spine": layer2_spine_benchmark()}


def check(results):
    """Compare against pins. Returns list of failure strings."""
    fails = []
    for row in results["layer1_er"]:
        if row.get("status") != "ok":
            continue
        pins = MIN_LAYER1.get(tuple(row["pair"]), {})
        for metric, floor in pins.items():
            if row[metric] < floor:
                fails.append(f"layer1 {row['pair']}: {metric} {row[metric]} < pin {floor}")
    for row in results["layer2_spine"]:
        if row.get("status") != "ok":
            continue
        pins = MIN_LAYER2.get(tuple(row["pair"]), {})
        for metric, floor in pins.items():
            if row[metric] < floor:
                fails.append(f"layer2 {row['pair']}: {metric} {row[metric]} < pin {floor}")
    return fails


def render_table(results):
    lines = []
    lines.append("**Layer 1 — ER-level vs oracle (precision / recall / F1):**")
    lines.append("")
    lines.append("| Pair | Oracle file | Oracle shared | Computed | Unparsed rows | Precision | Recall | F1 |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for r in results["layer1_er"]:
        if r.get("status") != "ok":
            lines.append(f"| {' × '.join(r['pair'])} | — | — | — | — | skipped: {r['reason']} | | |")
            continue
        note = " (superset expected — e1-scoped oracle)" if r["superset_expected"] else ""
        lines.append(
            f"| {' × '.join(r['pair'])} | {r['oracle_file']} | {r['oracle_shared']} | "
            f"{r['computed_shared']} | {r['unparsed_rows']} | {r['precision']}{note} | "
            f"{r['recall']} | {r['f1']} |")
    lines.append("")
    lines.append("**Layer 2 — spine (master_mappings) vs oracle-co-cited native ids:**")
    lines.append("")
    lines.append("| Pair | Join granularity | Oracle co-cited ids | Spine edge ids | Recovered | Oracle coverage | Corroboration rate |")
    lines.append("|---|---|---|---|---|---|---|")
    for r in results["layer2_spine"]:
        if r.get("status") != "ok":
            lines.append(f"| {' × '.join(r.get('pair', ['—']))} | skipped: {r['reason']} | | | | | |")
            continue
        lines.append(
            f"| {' × '.join(r['pair'])} | {r['join_granularity']} | {r['oracle_cocited_ids']} | "
            f"{r['master_edge_ids']} | {r['intersection']} | {r['oracle_coverage']} | "
            f"{r['corroboration_rate']} |")
    lines.append("")
    lines.append("SOC 2 × HIPAA Security has no spine-level row by design: the oracle's HIPAA side")
    lines.append("carries provider-proprietary identifiers, so only the ER layer is joinable.")
    return "\n".join(lines)


def write_doc(results):
    text = DOC_PATH.read_text(encoding="utf-8")
    if DOC_BEGIN not in text or DOC_END not in text:
        raise SystemExit(f"markers not found in {DOC_PATH}")
    head, rest = text.split(DOC_BEGIN, 1)
    _, tail = rest.split(DOC_END, 1)
    DOC_PATH.write_text(head + DOC_BEGIN + "\n\n" + render_table(results) + "\n\n" + DOC_END + tail,
                        encoding="utf-8")
    print(f"updated {DOC_PATH}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--check", action="store_true", help="fail (exit 1) if any metric fell below its pin")
    ap.add_argument("--json", metavar="OUT", help="write aggregate results JSON")
    ap.add_argument("--write-doc", action="store_true", help="refresh the generated table in docs/BENCHMARK.md")
    args = ap.parse_args()

    results = run_benchmark()
    print(render_table(results))

    if args.json:
        Path(args.json).write_text(json.dumps(results, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        print(f"wrote {args.json}")
    if args.write_doc:
        write_doc(results)

    fails = check(results)
    if fails:
        print("\n[BENCHMARK REGRESSIONS]")
        for f in fails:
            print("  FAIL:", f)
        if args.check:
            sys.exit(1)
    else:
        print("\n[all metrics at or above pins]")


if __name__ == "__main__":
    main()
